/// Кто может прочитать переписку.
///
/// Это решение владельца, а не техническая мелочь, поэтому оно записано
/// отдельным файлом и в одном месте: когда появится настоящая передача
/// сообщений, правила шифрования будут браться отсюда, а не додумываться
/// заново в коде экрана.
///
/// Договорённость:
/// - **рабочие** чаты владелец может прочитать. Это его компания, его люди и
///   его ответственность за то, что в ней написано;
/// - **личные** чаты между сотрудниками владелец прочитать не может. Никто,
///   кроме двух собеседников.
///
/// Разделение принципиальное: «доступ ко всему на всякий случай» превращает
/// личную переписку в служебную, и люди просто перестают ей пользоваться —
/// уходят в сторонний мессенджер, и смысл своего теряется.
library;

/// Тип переписки. От него зависит, кому шифруется ключ сообщения.
enum ChatKind {
  /// Рабочая: собеседники плюс корпоративный ключ владельца.
  work,

  /// Личная: только собеседники.
  personal,
}

/// Кому шифруется ключ конкретного сообщения.
///
/// Схема — конвертная: у каждого сообщения свой одноразовый ключ, само тело
/// шифруется им один раз, а дальше этот ключ шифруется отдельно под каждого,
/// кто вправе его прочитать. Так добавление ещё одного получателя стоит
/// несколько десятков байт, а не повторного шифрования всего сообщения.
///
/// Ровно по этой причине разница между рабочим и личным чатом сводится к
/// одному лишнему адресату ключа, а не к двум разным подсистемам.
class ChatEnvelopePolicy {
  /// Идентификатор корпоративного ключа. Не сам ключ — ключ живёт в хранилище
  /// устройства владельца, сюда попадает только имя, по которому его ищут.
  static const String corporateKeyId = 'wesios.corporate.v1';

  /// Получатели ключа сообщения.
  ///
  /// [recipients] — устройства собеседников. Возврат — то же самое плюс, для
  /// рабочего чата, корпоративный ключ.
  ///
  /// Дубликаты убираются: собеседник, который заодно и владелец, не должен
  /// получить свой экземпляр ключа дважды.
  static List<String> keyRecipients(
    ChatKind kind,
    Iterable<String> recipients,
  ) {
    final out = <String>{...recipients};
    if (kind == ChatKind.work) out.add(corporateKeyId);
    return out.toList()..sort();
  }

  /// Уезжает ли переписка этого типа с устройства.
  ///
  /// Пока — только рабочая, и это временно.
  ///
  /// Синхронизация складывает записи на сервер как есть, открытым текстом.
  /// Для рабочего чата это ровно то, о чём договорились: владелец его и так
  /// читает, а сервер — его. Для личного это было бы прямым нарушением
  /// подписи, которую человек видит в шапке: «переписку видят только
  /// собеседники». Обещание, которое интерфейс даёт, а хранилище не держит,
  /// хуже отсутствия обещания.
  ///
  /// Поэтому личные чаты и их сообщения остаются на устройстве до тех пор,
  /// пока не появится конвертное шифрование ([keyRecipients]): тогда на
  /// сервер поедет то, что владелец физически не расшифрует, и правило здесь
  /// станет `true` для обоих видов — вместе с тестом, который это закрепит.
  static bool travels(ChatKind kind) => kind == ChatKind.work;

  /// Может ли владелец прочитать переписку этого типа.
  ///
  /// Отдельным методом, потому что это должно быть написано в интерфейсе
  /// открытым текстом. Человек, начинающий личный чат, обязан видеть, что он
  /// личный, а начинающий рабочий — что он рабочий. Тихое разделение — это
  /// не приватность, а её видимость.
  static bool ownerCanRead(ChatKind kind) => kind == ChatKind.work;

  /// Подпись под чатом на экране.
  static String describe(ChatKind kind, {required bool russian}) =>
      switch (kind) {
        ChatKind.work => russian
            ? 'Рабочий чат. Переписку может прочитать владелец.'
            : 'Work chat. The owner can read it.',
        ChatKind.personal => russian
            ? 'Личный чат. Переписку видят только собеседники.'
            : 'Personal chat. Only the participants can read it.',
      };
}
