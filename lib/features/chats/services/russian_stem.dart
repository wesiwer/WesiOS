/// Грубое приведение русского слова к основе.
///
/// **Зачем.** Разбиение диалога на темы держится на том, что соседние куски
/// говорят об одном и том же — то есть переиспользуют слова. Без приведения
/// к основе «договор», «договора» и «договору» — три разных слова, и связь
/// между двумя соседними сообщениями об одном и том же не видна вовсе.
///
/// **Почему так грубо.** Настоящая морфология русского — это словарь на
/// сотни тысяч форм и несколько мегабайт в сборке ради задачи «понять, что
/// два сообщения про одно». Отсечение окончаний ошибается (например,
/// «полка» и «полк» сольются), но ошибается в обе стороны примерно
/// одинаково и на длинных текстах не мешает. Здесь важна не правильность
/// разбора, а стабильность: одно и то же слово должно давать одну и ту же
/// основу.
///
/// Алгоритм — усечённый Портер для русского: снимаем самые частые
/// словоизменительные окончания, начиная с длинных.
class RussianStem {
  RussianStem._();

  /// Окончания по убыванию длины: иначе «ами» превратится в «ам» + «и»
  /// и разные слова сольются сильнее, чем нужно.
  static const List<String> _endings = [
    'иями', 'ами', 'его', 'ему', 'ете', 'ешь', 'ими', 'ите', 'ишь', 'иях',
    'ого', 'ому', 'ыми', 'ями', 'ал', 'ам', 'ат', 'ах', 'ая', 'ев', 'ем',
    'ею', 'ие', 'ий', 'их', 'ла', 'ли', 'ло', 'на', 'но', 'ов', 'ой',
    'ом', 'ою', 'ти', 'ть', 'ут', 'ую', 'чь', 'ые', 'ый', 'ых', 'ют',
    'юю', 'ял', 'ят', 'ях', 'яя', 'а', 'е', 'и', 'й', 'о', 'у', 'ы', 'ь',
    'ю', 'я',
  ];

  /// Слова, которые встречаются в любом тексте и потому ничего не говорят
  /// о его теме. Без их отсева «и», «в», «не» оказались бы самыми частыми
  /// словами каждой темы, и все темы назывались бы одинаково.
  static const Set<String> stopWords = {
    'и', 'в', 'во', 'не', 'что', 'он', 'на', 'я', 'с', 'со', 'как', 'а',
    'то', 'все', 'она', 'так', 'его', 'но', 'да', 'ты', 'к', 'у', 'же',
    'вы', 'за', 'бы', 'по', 'только', 'ее', 'мне', 'было', 'вот', 'от',
    'меня', 'еще', 'нет', 'о', 'из', 'ему', 'теперь', 'когда', 'даже',
    'ну', 'вдруг', 'ли', 'если', 'уже', 'или', 'ни', 'быть', 'был',
    'него', 'до', 'вас', 'нибудь', 'опять', 'уж', 'вам', 'ведь', 'там',
    'потом', 'себя', 'ничего', 'ей', 'может', 'они', 'тут', 'где', 'есть',
    'надо', 'ней', 'для', 'мы', 'тебя', 'их', 'чем', 'была', 'сам',
    'чтоб', 'без', 'будто', 'человек', 'чего', 'раз', 'тоже', 'себе',
    'под', 'жизнь', 'будет', 'ж', 'кто', 'этот', 'того', 'потому',
    'этого', 'какой', 'совсем', 'ним', 'здесь', 'этом', 'один', 'почти',
    'мой', 'тем', 'чтобы', 'нее', 'кажется', 'сейчас', 'были', 'куда',
    'зачем', 'всех', 'никогда', 'можно', 'при', 'наконец', 'два', 'об',
    'другой', 'хоть', 'после', 'над', 'больше', 'тот', 'через', 'эти',
    'нас', 'про', 'всего', 'них', 'какая', 'много', 'разве', 'сказал',
    'три', 'эту', 'моя', 'впрочем', 'хорошо', 'свою', 'этой', 'перед',
    'иногда', 'лучше', 'чуть', 'том', 'нельзя', 'такой', 'им', 'более',
    'всегда', 'конечно', 'всю', 'между', 'ок', 'привет', 'спасибо',
    'пожалуйста',
  };

  /// Основа слова. Короткие слова не трогаем: от «дом» после отсечения
  /// осталось бы «до», и он слился бы с предлогом.
  static String of(String word) {
    final w = word.toLowerCase().replaceAll('ё', 'е');
    if (w.length <= 4) return w;
    for (final e in _endings) {
      if (w.length - e.length >= 3 && w.endsWith(e)) {
        return w.substring(0, w.length - e.length);
      }
    }
    return w;
  }

  /// Значимые основы текста: без знаков, без служебных слов, без чисел.
  static List<String> tokens(String text) {
    final words = text
        .toLowerCase()
        .replaceAll(RegExp(r'[^а-яёa-z0-9\s-]'), ' ')
        .split(RegExp(r'\s+'));
    final out = <String>[];
    for (final w in words) {
      final clean = w.trim();
      if (clean.length < 3) continue;
      if (stopWords.contains(clean)) continue;
      // Числа не описывают тему: «5000» встретится и в разговоре про
      // зарплату, и в разговоре про метраж склада.
      if (RegExp(r'^[0-9]+$').hasMatch(clean)) continue;
      final stem = of(clean);
      if (stem.length < 3) continue;
      if (stopWords.contains(stem)) continue;
      out.add(stem);
    }
    return out;
  }
}
