import 'dart:async';

import '../../../core/sync/sync_endpoint.dart';
import '../../../core/sync/sync_engine.dart';

/// Обмен перепиской, пока чат открыт.
///
/// **Почему не «настоящий realtime».** У PocketBase есть подписка на
/// изменения, и когда-нибудь она здесь будет. Но постоянное соединение —
/// это отдельная работа: обрывы, переподключение, поведение при спящем
/// экране, расход батареи. Сделанное наспех, оно даёт худший из миров —
/// соединение, которое считается живым, а сообщений не приносит.
///
/// Пока — короткий опрос и только когда человек смотрит в переписку.
/// Задержка в несколько секунд заметна, но она честная: сообщение
/// действительно приходит, и видно, когда именно.
///
/// Обмениваемся **только чатами и сообщениями**: таскать при этом операции,
/// задачи, статьи и состав — лишняя работа для сервера с одним ядром.
class ChatSync {
  /// Как часто спрашивать сервер, пока открыт чат.
  ///
  /// Пятнадцать секунд — компромисс. Пять превращают разговор двоих в
  /// постоянную нагрузку на машину, где кроме него живёт всё остальное;
  /// минута ощущается как «не работает».
  static const Duration interval = Duration(seconds: 15);

  static const Set<String> _collections = {'chats', 'messages'};

  static Timer? _timer;
  static int _watchers = 0;

  /// Кто-то открыл переписку.
  ///
  /// Счётчик, а не флаг: экранов может быть открыто несколько (чат поверх
  /// списка), и закрытие одного не должно останавливать обмен для
  /// оставшихся.
  static void watch() {
    _watchers++;
    if (_timer != null) return;
    if (!SyncEndpoint.enabled || !SyncEndpoint.isConfigured) return;
    _timer = Timer.periodic(interval, (_) => _tick());
    // Первый обмен сразу: ждать пятнадцать секунд, только что войдя в чат,
    // незачем.
    _tick();
  }

  static void unwatch() {
    if (_watchers > 0) _watchers--;
    if (_watchers > 0) return;
    _timer?.cancel();
    _timer = null;
  }

  /// Обменяться прямо сейчас — после того, как человек что-то отправил.
  static void nudge() => _tick();

  static void _tick() {
    if (!SyncEndpoint.enabled || !SyncEndpoint.isConfigured) return;
    // Проход уже идёт — второй читал бы боксы, пока первый их переписывает.
    if (SyncEngine.busy.value) return;
    // Неудача здесь ничего не значит: связи нет — попробуем через
    // пятнадцать секунд. Жаловаться человеку на каждый неудачный опрос
    // означало бы завалить его сообщениями в метро.
    unawaited(SyncEngine.run(only: _collections)
        .catchError((_) => SyncReport(at: DateTime.now())));
  }

  /// Только для тестов: остановить всё и забыть счётчик.
  static void reset() {
    _timer?.cancel();
    _timer = null;
    _watchers = 0;
  }
}
