import 'package:flutter_test/flutter_test.dart';
import 'package:wesios/features/chats/services/topic_chunker.dart';

/// Измеряемое качество разбиения на темы.
///
/// **Зачем отдельный файл с числом вместо обычных тестов.** Остальные тесты
/// проверяют случаи, под которые алгоритм и написан: долгая пауза, слово
/// «кстати», явная смена склада на прайс. Они полезны — но доказывают лишь
/// то, что заложенные правила работают, а не что система справляется с
/// настоящей перепиской.
///
/// Здесь набор нарочно неудобных диалогов, каждый с известным правильным
/// ответом. Тест считает, на скольких алгоритм не ошибся, и печатает число.
/// Порог взят по фактическому поведению, а не выдуман: он фиксирует, что
/// качество не упало, и его надо поднимать по мере улучшений.
///
/// Так честнее, чем набор отдельных тестов на каждый сложный случай:
/// половина из них сегодня падала бы, и их пришлось бы либо удалить, либо
/// пометить skip — и то и другое означает «мы про это не знаем».
void main() {
  final day = DateTime.utc(2026, 8, 4, 10);

  List<ChunkInput> dialog(List<String> lines) {
    var at = day;
    final out = <ChunkInput>[];
    for (var i = 0; i < lines.length; i++) {
      final parts = lines[i].split('|');
      at = at.add(Duration(minutes: int.parse(parts[1])));
      out.add(ChunkInput(
          id: 'm$i', authorId: parts[0], at: at, text: parts[2]));
    }
    return out;
  }

  /// Один случай: диалог и ожидание — должна ли пройти граница.
  ///
  /// `splitNear` — позиция, рядом с которой граница обязана быть (±1: точное
  /// сообщение, на котором сменилась тема, спорно и для человека).
  /// null — границ быть не должно вовсе.
  ({String name, List<ChunkInput> messages, int? splitNear}) c(
    String name,
    List<String> lines,
    int? splitNear,
  ) =>
      (name: name, messages: dialog(lines), splitNear: splitNear);

  final cases = [
    // 6.1 — одна тема, разорванная долгой паузой. Ночь между репликами не
    // делает разговор о том же двумя разными разговорами.
    c('одна тема после ночного перерыва', [
      'a|0|Отгрузили десять паллет на склад в Пушкино',
      'b|2|Принял, накладные подпишу завтра',
      'a|3|Там ещё две паллеты остались, не влезли в машину',
      'b|900|Доброе утро, накладные подписал, паллеты забрал',
      'a|4|Отлично, тогда по складу закрыли',
      'b|3|Да, по складу всё',
    ], null),

    // 6.2 — разные темы, а слова похожие: «счёт» бухгалтерский и «счёт»
    // банковский, «договор» аренды и «договор» поставки.
    c('разные темы с похожей лексикой', [
      'a|0|Договор аренды склада надо продлить до конца года',
      'b|2|Аренда дорожает, но продлевать выгоднее чем переезжать',
      'a|3|Хорошо, готовь допсоглашение по аренде',
      'b|4|Кстати договор поставки с Ветал тоже заканчивается',
      'a|2|Поставка это отдельная история, там цены пересматривают',
      'b|3|Да, по поставке нужно новое приложение к договору',
    ], 3),

    // 6.3 — одна тема, но словарь меняется: начали про деньги, продолжили
    // про людей, а речь всё время про одну задачу.
    c('одна тема при смене словаря', [
      'a|0|Зарплату за август считаем по новой ставке',
      'b|2|По новой это плюс двенадцать процентов к фонду',
      'a|3|Да, зато текучка перестанет съедать обучение новичков',
      'b|2|Новички у нас три месяца выходят на норму',
      'a|3|Вот именно поэтому и поднимаем',
      'b|2|Согласен, считаю по новой ставке',
    ], null),

    // 6.6 — чередование A → B → A. Возврат к первой теме не должен
    // выглядеть как третья новая тема.
    c('возврат к первой теме', [
      'a|0|По складу в Пушкино остаток двести коробок',
      'b|2|Понял, отгрузим на неделе',
      'a|60|Отдельно: зарплата в четверг, предупреди людей',
      'b|3|Предупрежу сегодня же',
      'a|60|Вернёмся к складу: двести коробок надо вывезти до пятницы',
      'b|3|По складу успеем, машина в четверг',
    ], 2),

    // 6.7 — ответ без вопросительного знака. Реплика «а когда» это вопрос,
    // и следующая за ней реплика — ответ, а не новая тема.
    c('вопрос без знака вопроса', [
      'a|0|Прайс обновили, новые цены с понедельника',
      'b|2|А когда рассылать клиентам',
      'a|3|В пятницу вечером, чтобы в понедельник уже знали',
      'b|2|Понял, подготовлю рассылку в четверг',
    ], null),

    // Явная смена темы — контрольный случай. Если алгоритм не видит её,
    // сломано что-то фундаментальное.
    c('явная смена темы после паузы', [
      'a|0|Прайс на комплектующие поднялся у поставщика на восемь процентов',
      'b|2|Восемь это много, будем искать второго поставщика',
      'a|3|Поищи, у Ветал вроде дешевле было',
      'b|240|Отдельная тема: аренда склада заканчивается в ноябре',
      'a|3|Про аренду надо решать сейчас, иначе поднимут',
      'b|2|Да, склад надо продлевать заранее',
    ], 3),

    // Ровный разговор об одном. Границ быть не должно.
    c('ровный разговор об одном', [
      'a|0|Договор с Ветал подписали вчера, скан у меня',
      'b|2|Пришли скан, приложу к делу',
      'a|2|Отправил на почту, там же приложение с ценами',
      'b|2|Вижу, цены совпадают с тем что обсуждали',
      'a|2|Тогда всё, договор закрыт',
    ], null),

    // Короткие реплики без содержания не должны рождать границы.
    c('короткие реплики', [
      'a|0|Ок',
      'b|2|Да',
      'a|2|Понял',
      'b|2|Хорошо',
      'a|2|Договорились',
    ], null),
  ];

  /// Прошёл ли случай.
  bool passes(({String name, List<ChunkInput> messages, int? splitNear}) t) {
    final plan = TopicChunker.plan(t.messages);
    // Границы — это начала кусков, кроме самого первого.
    final borders = [
      for (final ch in plan.chunks)
        if (ch.start > 0) ch.start,
    ];
    // Вопросы к человеку считаем предложенными границами: система про них
    // не уверена, но место указала.
    final asked = [for (final q in plan.questions) q.index];
    final proposed = {...borders, ...asked};

    if (t.splitNear == null) return proposed.isEmpty;
    return proposed.any((p) => (p - t.splitNear!).abs() <= 1);
  }

  test('качество разбиения на сложных диалогах измерено', () {
    final failed = <String>[];
    for (final t in cases) {
      if (!passes(t)) failed.add(t.name);
    }
    final score = cases.length - failed.length;

    // Печатаем всегда: число здесь — главный результат, а не оформление.
    // ignore: avoid_print
    print('Разбиение на темы: $score из ${cases.length}');
    if (failed.isNotEmpty) {
      // ignore: avoid_print
      print('Не справляется: ${failed.join('; ')}');
    }

    // Порог — по фактическому поведению, а не по желаемому. Он не про
    // «хорошо», а про «не хуже, чем было»: любое ухудшение уронит тест, а
    // улучшение потребует поднять число здесь же, осознанно.
    //
    // Было 4 из 8. Стало 6 после двух правок: расхождение словарей теперь
    // ослабляется, когда слов слишком мало, чтобы ему верить, и долгая
    // пауза перестала резать разговор, продолженный теми же словами.
    //
    // Два оставшихся случая — «одна тема после ночного перерыва» и «одна
    // тема при смене словаря» — по словам не решаются в принципе. В первом
    // после ночи говорят о том же, но чуть иначе; во втором говорят об
    // одном деле совершенно разными словами. Отличить это от настоящей
    // смены темы можно только поняв смысл — это работа модели, и ровно
    // ради этих случаев она в чатах и нужна. Подгонять под них константы
    // значило бы подстроить алгоритм под восемь диалогов из этого файла.
    expect(score, greaterThanOrEqualTo(6),
        reason: 'качество разбиения упало ниже измеренного уровня');
  });

  test('контрольные случаи обязаны проходить всегда', () {
    // Эти два — не «сложные», а базовые. Их провал означает, что сломано
    // основное, и отдельным порогом их прикрывать нельзя.
    for (final name in ['явная смена темы после паузы', 'короткие реплики']) {
      final t = cases.firstWhere((x) => x.name == name);
      expect(passes(t), isTrue, reason: name);
    }
  });
}
