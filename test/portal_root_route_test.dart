import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// Корневой маршрут портала не должен забирать себе весь домен.
///
/// В роутере PocketBase образец `"/"` совпадает не с корнем, а с любым
/// адресом, который не подобрал никто другой. Из-за одной этой строки
/// `https://api.wesi-inc.ru/wesios-status.json` отвечал перенаправлением на
/// портал — и вместе с ним стал недостижим весь `pb_public`. Приложение
/// показывало «Агент указан, но не отвечает», хотя агент был ни при чём.
///
/// Проверка идёт по исходнику хука: поднять здесь настоящий PocketBase
/// нечем, а разница между `"/"` и `"/{$}"` — ровно одна строка, и увидеть
/// её глазами проще, чем воспроизвести.
void main() {
  test('корень домена не превращается в ловушку для всех адресов', () {
    final source =
        File('server/pb_hooks/employee_portal_static.pb.js').readAsStringSync();

    expect(
      source.contains('routerAdd("GET", "/{\$}"'),
      isTrue,
      reason: 'корень должен совпадать только с корнем',
    );
    expect(
      RegExp(r'routerAdd\(\s*"GET"\s*,\s*"/"\s*,').hasMatch(source),
      isFalse,
      reason: 'образец "/" уносит на портал любой несовпавший адрес — '
          'вместе с файлом агента и всем остальным в pb_public',
    );
  });
}
