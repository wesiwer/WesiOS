/// Права доступа к данным WesiOS — в коде, а не в памяти.
///
/// **Зачем миграция, если есть скрипт.** Скрипт надо вспомнить и запустить.
/// Коллекцию, заведённую руками в панели, он до этой правки вообще обходил
/// стороной — и на живом сервере она полгода могла стоять нараспашку.
/// Миграция применяется сама, при каждом запуске PocketBase, и лежит в
/// репозитории, где её видно на код-ревью.
///
/// **Пустое правило в PocketBase означает «всем», а не «никому».** Это
/// ловушка, на которой всё и сломалось: коллекция без выставленных правил
/// выглядит закрытой, а на деле любой человек в интернете читает и
/// дописывает записи компании. Снаружи такой сервер работает идеально —
/// именно поэтому дыра не обнаруживается сама.
///
/// Правило `owner = @request.auth.id`: запись видна и доступна только тому,
/// кто её положил. Общий доступ сотрудников появится через поле `org` —
/// оно в схеме есть с самого начала, и тогда правило станет проверкой
/// принадлежности к организации, а не к человеку.
migrate(
  (app) => {
    // Записи приложения.
    try {
      const records = app.findCollectionByNameOrId('wesios_records');
      const mine = 'owner = @request.auth.id';
      records.listRule = mine;
      records.viewRule = mine;
      records.createRule = mine;
      records.updateRule = mine;
      records.deleteRule = mine;
      app.save(records);
    } catch (e) {
      // Коллекции ещё нет — её создаст setup-collections.sh, уже с
      // правилами. Ронять запуск сервера из-за этого нельзя.
      console.log('wesios_records: пропускаю — ' + e);
    }

    // Люди. Встроенная коллекция приезжает с открытым списком: кто угодно
    // запрашивает перечень и видит почты всех сотрудников. Плюс открытая
    // регистрация — посторонний заводит себе учётку сам.
    try {
      const users = app.findCollectionByNameOrId('users');
      const self = 'id = @request.auth.id';
      users.listRule = self;
      users.viewRule = self;
      users.updateRule = self;
      // null — «только администратор». Пустая строка означала бы обратное:
      // «кто угодно». Разница в один символ и в весь смысл.
      users.createRule = null;
      users.deleteRule = null;
      app.save(users);
    } catch (e) {
      console.log('users: пропускаю — ' + e);
    }
  },
  (app) => {
    // Отката нет намеренно.
    //
    // «Откатить» здесь означало бы снова открыть данные наружу. Миграция,
    // умеющая это сделать одной командой, рано или поздно будет запущена по
    // ошибке. Если правила понадобится изменить — это новая миграция с
    // новым решением, записанным явно.
    console.log('Откат прав доступа не предусмотрен — см. комментарий.');
  },
);
