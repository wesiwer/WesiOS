test('video adapter creates one bounded Veo operation', async () => {
  let url = '';
  let body = null;
  const result = await startGoogleVideo(
    {prompt: 'Короткий кинематографичный пролёт', aspectRatio: '9:16', resolution: '1080p', durationSeconds: '4', quality: 'fast'},
    'gemini-key',
    {fetchImpl: async (u, init) => {
      url = String(u);
      body = JSON.parse(init.body);
      return jsonResponse({name: 'operations/video-test-1'});
    }},
  );
  assert.equal(result.ok, true);
  assert.match(url, /veo-3\.1-fast-generate-preview:predictLongRunning$/);
  assert.equal(body.parameters.numberOfVideos, 1);
  assert.equal(body.parameters.aspectRatio, '9:16');
  assert.equal(body.parameters.durationSeconds, '8', '1080p must use an 8-second request');
});

test('video status keeps provider URI in server-to-server result only', async () => {
  const result = await getGoogleVideoStatus(
    'operations/video-test-1',
    'gemini-key',
    {fetchImpl: async () => jsonResponse({
      done: true,
      response: {generateVideoResponse: {generatedSamples: [{video: {uri: 'https://provider.example/private/video'}}]}},
    })},
  );
  assert.equal(result.ok, true);
  assert.equal(result.done, true);
  assert.equal(result.failed, false);
  assert.equal(result.providerUri, 'https://provider.example/private/video');
});

